def compile_dut(tmp, name, dctl, ids=None):
    src = Path(tmp) / (name + ".c")
    src.write_text(HARNESS % {"enum": ("enum { %s };" % ", ".join(ids)) if ids else "", "dut": dctl})
    exe = Path(tmp) / name
    r = subprocess.run(["cc", "-O0", "-Wall", "-Wno-unused-function", str(src), "-o", str(exe), "-lm"],
                       capture_output=True, text=True)
    if r.returncode or r.stderr.strip():
        raise SystemExit("C compile of %s failed or warned:\n%s" % (name, r.stderr))
    return exe


def f32(a):
    return np.asarray(a, float).astype(np.float32).astype(float)


def make_rows(basis, hold, C, k):
    """Harness rows (float32-rounded, so the double reference sees the same inputs) and the matching C, k."""
    n = len(k)
    C = f32(np.broadcast_to(np.asarray(C, float).reshape(-1, 9), (n, 9))); k = f32(k)
    R = np.column_stack([np.full(n, basis, float), np.full(n, hold, float), C, k])
    return R, C.reshape(n, 3, 3), k


def random_C(rng, n, dr=DIAG_RANGE, orr=OFF_RANGE):
    C = rng.uniform(*orr, (n, 9))
    for i in (0, 4, 8):
        C[:, i] = rng.uniform(*dr, n)
    return C



def emit_basis(key, Sn, first):
    """Sn off-diagonals (m) and Sn^-1 (n) for one stock, selected by `basis == key`."""
    Si = np.linalg.inv(Sn)
    f = lambda v: "%.9ef" % v
    return "\n".join([
        "    %sif (basis == %s)" % ("" if first else "else ", key), "    {",
        "        m01 = %s; m02 = %s;" % (f(Sn[0, 1]), f(Sn[0, 2])),
        "        m10 = %s; m12 = %s;" % (f(Sn[1, 0]), f(Sn[1, 2])),
        "        m20 = %s; m21 = %s;" % (f(Sn[2, 0]), f(Sn[2, 1])),
        "        n00 = %s; n01 = %s; n02 = %s;" % tuple(f(v) for v in Si[0]),
        "        n10 = %s; n11 = %s; n12 = %s;" % tuple(f(v) for v in Si[1]),
        "        n20 = %s; n21 = %s; n22 = %s;" % tuple(f(v) for v in Si[2]),
        "    }"])



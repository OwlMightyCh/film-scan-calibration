def ui_params(rows, slider):
    lines = []
    for i in UI_ORDER:
        n, lb = NAMES[i], LABELS[i]
        d, lo, hi = (1.0, *DIAG_RANGE) if i % 4 == 0 else (0.0, *OFF_RANGE)
        lines.append("DEFINE_UI_PARAMS(%s, %s, DCTLUI_SLIDER_FLOAT, %.1f, %.1f, %.1f, 0.001)" % (n, lb, d, lo, hi))
    lines.append("DEFINE_UI_PARAMS(hold, Hold Neutral, DCTLUI_CHECK_BOX, 0)")
    if slider:
        key = lambda i, stem: "%d" % (i + 1)
        lines.append("DEFINE_UI_PARAMS(basis, Layer Basis, DCTLUI_SLIDER_INT, 0, 0, %d, 1)" % len(rows))
        kind, note = "numbered int slider", ""
    else:
        key = lambda i, stem: "LB_" + stem.upper()
        ids = ", ".join(["LB_OFF"] + [key(i, r["stem"]) for i, r in enumerate(rows)])
        labels = ", ".join(["Off"] + [r["name"] for r in rows])
        lines.append("DEFINE_UI_PARAMS(basis, Layer Basis, DCTLUI_COMBO_BOX, 0, { %s }, { %s })" % (ids, labels))
        kind, note = "named menu", (" If Resolve refuses the menu, regenerate with --slider for\n"
                                    "// a numbered slider (same numbers as the list above).")
    return "\n".join(lines), key, kind, note


def write_dctl(path, rows, slider):
    legend = "\n".join("//  %2d  %-18s Sn off-diagonals m01 m02 m10 m12 m20 m21 = %s, cond2 %.3f"
                       % (i + 1, r["stem"], " ".join("%.4f" % r["Sn"][a, b] for a, b in
                                                     ((0, 1), (0, 2), (1, 0), (1, 2), (2, 0), (2, 1))), r["cond"])
                       for i, r in enumerate(rows))
    params, key, kind, note = ui_params(rows, slider)
    basis = "\n".join(emit_basis(key(i, r["stem"]), r["Sn"], i == 0) for i, r in enumerate(rows))
    Path(path).parent.mkdir(parents=True, exist_ok=True)   # dctl/ is not in a clone
    Path(path).write_text(HEAD % {"legend": legend, "uikind": kind, "uinote": note}
                          + BODY % {"params": params, "basis": basis})
    return ["LB_OFF"] + ["LB_" + r["stem"].upper() for r in rows]


def write_slope_ref(path, rows):
    """SLOPE_REF with the named-menu parameters and the same per-stock tables as the shipped file."""
    params, key, _, _ = ui_params(rows, False)
    basis = "\n".join(emit_basis(key(i, r["stem"]), r["Sn"], i == 0) for i, r in enumerate(rows))
    Path(path).write_text(SLOPE_REF % {"params": params, "basis": basis})


# ---------------- double reference ----------------
def reference(basis_Sn, C, hold, k):
    """out = P + M (k - P); basis_Sn None = Off. C (n,3,3) or (3,3); k (n,3)."""
    C = np.broadcast_to(C, (len(k), 3, 3))
    if basis_Sn is None:
        M = C.copy()
    else:
        M = basis_Sn @ C @ np.linalg.inv(basis_Sn)
    if hold:
        M = M.copy()
        d = 1.0 - M.sum(2)
        for i in range(3):
            M[:, i, i] += d[:, i]
    return P + np.einsum("nij,nj->ni", M, k - P)


